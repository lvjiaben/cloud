// This file defines public plugin runtime-state API DTOs.

package v1

import (
	"lina-core/pkg/statusflag"

	"github.com/gogf/gf/v2/frame/g"
)

// DynamicListReq is the request for querying public dynamic-plugin states.
type DynamicListReq struct {
	g.Meta `path:"/plugins/dynamic" method:"get" tags:"Plugin Management" summary:"Query plugin running status" dc:"Returns the minimum set of running states required for the frontend public interface layer to render the plugin Slot, which can be used by the login page and layout interface to determine whether the plugin content should be displayed in the anonymous or logged-in state."`
}

// DynamicListRes is the response for querying public dynamic-plugin states.
type DynamicListRes struct {
	List []*PluginDynamicItem `json:"list" dc:"Plugin running status list" eg:"[]"`
}

// PluginDynamicItem represents public dynamic state of one plugin.
type PluginDynamicItem struct {
	Id               string                              `json:"id" dc:"Plugin unique identifier" eg:"demo-dynamic"`
	Installed        statusflag.Installation             `json:"installed" dc:"Installation status: 1=Installed/Integrated 0=Not installed" eg:"1"`
	Enabled          statusflag.Enabled                  `json:"enabled" dc:"Enabled status: 1=enabled 0=disabled" eg:"1"`
	Version          string                              `json:"version" dc:"The current effective version number of the plugin; if it is only uploaded without switching, it will still return to the old version." eg:"v0.1.0"`
	Generation       int64                               `json:"generation" dc:"The plugin's current effective generation number; the frontend can use this to determine whether the current plugin page needs to be refreshed." eg:"3"`
	StatusKey        string                              `json:"statusKey" dc:"The location key name of the plugin status in the system plugin registry" eg:"sys_plugin.status:demo-dynamic"`
	RuntimeState     RuntimeState                        `json:"runtimeState" dc:"Plugin runtime upgrade state. Frontend business entries may execute only when this value is normal or empty for old servers." eg:"normal"`
	Type             PluginType                          `json:"type" dc:"Plugin runtime type used to select the governed source-page or isolated dynamic-page host." eg:"dynamic"`
	CustomerSurfaces []*PluginRuntimeFrontendSurfaceItem `json:"customerSurfaces,omitempty" dc:"Effective signed-in customer-center surfaces after host slot and route governance." eg:"[]"`
}

// PluginRuntimeFrontendSurfaceItem is one host-ready effective surface. Its
// route and asset URL are generated by the host rather than trusted from the
// plugin as absolute locations.
type PluginRuntimeFrontendSurfaceItem struct {
	PluginId           string     `json:"pluginId" dc:"Plugin owning this frontend surface." eg:"ssl-provider"`
	PluginType         PluginType `json:"pluginType" dc:"Runtime type of the owning plugin." eg:"dynamic"`
	Key                string     `json:"key" dc:"Stable surface key within the matching host." eg:"certificates"`
	Version            string     `json:"version" dc:"Surface contract version." eg:"v1"`
	Title              string     `json:"title" dc:"Plugin-declared menu and page title." eg:"SSL certificates"`
	Icon               string     `json:"icon,omitempty" dc:"Host-supported icon identifier." eg:"lucide:shield-check"`
	Permission         string     `json:"permission,omitempty" dc:"Permission required by the host surface." eg:"ssl-provider:certificates:view"`
	Slot               string     `json:"slot" dc:"Published host slot selected by the plugin." eg:"customer.products"`
	RoutePath          string     `json:"routePath" dc:"Host-generated route inside the plugin namespace." eg:"/account/plugins/ssl-provider/certificates"`
	Entry              string     `json:"entry" dc:"Normalized plugin-relative source entry." eg:"customer/index.html"`
	EntryUrl           string     `json:"entryUrl,omitempty" dc:"Version-frozen host asset URL for dynamic plugins." eg:"/x-assets/ssl-provider/v1.0.0/customer/index.html"`
	Status             string     `json:"status,omitempty" dc:"Plugin-declared business availability state." eg:"active"`
	BridgeCapabilities []string   `json:"bridgeCapabilities,omitempty" dc:"Requested versioned page-bridge capabilities." eg:"[\"identity.v1\"]"`
}
