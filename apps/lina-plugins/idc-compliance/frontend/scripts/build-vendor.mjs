import { createHash } from "node:crypto";
import {
  copyFile,
  mkdir,
  readFile,
  readdir,
  rename,
  rm,
  stat,
  writeFile,
} from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const vendorDir = join(frontendRoot, "vendor");
const temporaryDir = join(frontendRoot, `.vendor-build-${process.pid}`);
const checkOnly = process.argv.includes("--check");

function assertInsideFrontend(target) {
  const relativeTarget = relative(frontendRoot, target);
  if (
    !relativeTarget ||
    relativeTarget.startsWith("..") ||
    relativeTarget.includes(":")
  ) {
    throw new Error(`refusing to manage path outside plugin frontend: ${target}`);
  }
}

async function bundle(entryPoint, outfile, external = []) {
  await build({
    banner: {
      js: "// Generated by idc-compliance/frontend/scripts/build-vendor.mjs.",
    },
    bundle: true,
    entryPoints: [entryPoint],
    external,
    format: "esm",
    legalComments: "eof",
    logLevel: "warning",
    minify: true,
    outfile,
    platform: "browser",
    sourcemap: false,
    target: ["es2022"],
  });
}

async function fileDigest(filePath) {
  const contents = await readFile(filePath);
  return {
    bytes: contents.byteLength,
    sha256: createHash("sha256").update(contents).digest("hex"),
  };
}

async function buildManifest(directory) {
  const files = (
    await readdir(directory, { withFileTypes: true })
  )
    .filter((entry) => entry.isFile() && entry.name !== "manifest.json")
    .map((entry) => entry.name)
    .sort();
  const manifest = { formatVersion: 1, files: {} };
  for (const name of files) {
    manifest.files[name] = await fileDigest(join(directory, name));
  }
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

async function assertNoBusinessBareImports(directory) {
  for (const name of ["contract-editor.mjs", "pdf.mjs", "pdf.worker.mjs"]) {
    const contents = await readFile(join(directory, name), "utf8");
    if (/from[\s]*(?:\(|)["'](?:@tiptap\/|pdfjs-dist)/u.test(contents)) {
      throw new Error(`${name} still imports an IDC business dependency`);
    }
  }
}

async function assertDirectoriesMatch(expectedDir, actualDir) {
  const expectedManifest = await buildManifest(expectedDir);
  const actualManifest = await buildManifest(actualDir);
  if (expectedManifest !== actualManifest) {
    throw new Error(
      "plugin vendor output is stale; run pnpm --dir frontend run build",
    );
  }
}

async function main() {
  assertInsideFrontend(temporaryDir);
  assertInsideFrontend(vendorDir);
  await rm(temporaryDir, { force: true, recursive: true });
  await mkdir(temporaryDir, { recursive: true });

  await Promise.all([
    bundle(
      join(frontendRoot, "vendor-src", "contract-editor.ts"),
      join(temporaryDir, "contract-editor.mjs"),
      ["vue"],
    ),
    bundle(
      join(frontendRoot, "vendor-src", "pdf.ts"),
      join(temporaryDir, "pdf.mjs"),
    ),
    bundle(
      join(frontendRoot, "node_modules", "pdfjs-dist", "build", "pdf.worker.mjs"),
      join(temporaryDir, "pdf.worker.mjs"),
    ),
  ]);

  await Promise.all([
    copyFile(
      join(frontendRoot, "vendor-types", "contract-editor.d.mts"),
      join(temporaryDir, "contract-editor.d.mts"),
    ),
    copyFile(
      join(frontendRoot, "vendor-types", "pdf.d.mts"),
      join(temporaryDir, "pdf.d.mts"),
    ),
  ]);
  await assertNoBusinessBareImports(temporaryDir);
  await writeFile(
    join(temporaryDir, "manifest.json"),
    await buildManifest(temporaryDir),
    "utf8",
  );

  if (checkOnly) {
    const vendorInfo = await stat(vendorDir).catch(() => undefined);
    if (!vendorInfo?.isDirectory()) {
      throw new Error(
        "plugin vendor output is missing; run pnpm --dir frontend run build",
      );
    }
    await assertDirectoriesMatch(vendorDir, temporaryDir);
    await rm(temporaryDir, { force: true, recursive: true });
    return;
  }

  await rm(vendorDir, { force: true, recursive: true });
  await rename(temporaryDir, vendorDir);
}

await main().catch(async (error) => {
  await rm(temporaryDir, { force: true, recursive: true }).catch(() => {});
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
