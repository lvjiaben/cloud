// Customer privacy request API creates an export or deletion request for the signed-in customer. Legal and business retention is evaluated before deletion.

package v1

import "github.com/gogf/gf/v2/frame/g"

// CustomerPrivacyRequestCreateReq creates an export or deletion request.
type CustomerPrivacyRequestCreateReq struct {
	g.Meta          `path:"/account/compliance/privacy/requests" method:"post" tags:"IDC Compliance Account" summary:"Create my privacy request" dc:"Create or safely replay one ownership-only export or deletion request. Legal, contract, tax, dispute, and audit evidence is reviewed before deletion."`
	RequestTypeCode string `json:"requestTypeCode" v:"required|in:export,delete" dc:"Requested action" eg:"export"`
	IdempotencyKey  string `json:"idempotencyKey" v:"required|length:16,128" dc:"Random replay key generated by the customer application" eg:"privacy-request-0123456789abcdef"`
}

// CustomerPrivacyRequestCreateRes returns the created or replayed request.
type CustomerPrivacyRequestCreateRes struct {
	Request CustomerPrivacyRequest `json:"request" dc:"Created or replayed customer-owned request" eg:"{}"`
}
