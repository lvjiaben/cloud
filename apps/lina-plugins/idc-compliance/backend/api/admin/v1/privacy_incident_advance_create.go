// Privacy incident advance API moves exactly one response stage with optimistic concurrency. External notification requires an explicit confirmation flag.

package v1

import "github.com/gogf/gf/v2/frame/g"

type PrivacyIncidentAdvanceCreateReq struct {
	g.Meta                      `path:"/admin/compliance/privacy/incidents/{incidentNo}/advances" method:"post" tags:"IDC Compliance Privacy" summary:"Advance a privacy incident" dc:"Move exactly one response stage. External notification is never sent automatically and requires explicit confirmation at its stage." permission:"idc:admin:compliance:privacy:incident"`
	IncidentNo                  string `json:"incidentNo" in:"path" v:"required|max-length:40" dc:"Opaque privacy incident number" eg:"PIN_0123456789abcdef0123456789abcdef"`
	ExpectedVersion             int64  `json:"expectedVersion" v:"required|min:1" dc:"Incident version last read by the administrator" eg:"1"`
	NextStageCode               string `json:"nextStageCode" v:"required|in:contained,assessed,notification_pending,notification_confirmed,remediating,resolved" dc:"Next response stage: contained, assessed, notification_pending, notification_confirmed, remediating, or resolved" eg:"contained"`
	SafeNote                    string `json:"safeNote" v:"required|max-length:2000" dc:"Bounded response note without raw affected records or credentials" eg:"Sensitive export access has been disabled"`
	ConfirmExternalNotification bool   `json:"confirmExternalNotification" dc:"Explicit confirmation required only for notification_confirmed" eg:"false"`
	IdempotencyKey              string `json:"idempotencyKey" v:"required|length:16,128" dc:"Random replay key generated by the administrator application" eg:"privacy-advance-0123456789abcdef"`
}

type PrivacyIncidentAdvanceCreateRes struct {
	Item PrivacyIncidentItem `json:"item" dc:"Updated incident and complete safe timeline" eg:"{}"`
}
