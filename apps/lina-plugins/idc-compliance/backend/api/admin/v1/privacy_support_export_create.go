// Privacy support export API creates a local redacted diagnostic document after separate confirmation. It never opens remote access or exports raw private data.

package v1

import "github.com/gogf/gf/v2/frame/g"

type PrivacySupportExportCreateReq struct {
	g.Meta                    `path:"/admin/compliance/privacy/support-exports" method:"post" tags:"IDC Compliance Privacy" summary:"Generate a local redacted support export" dc:"Generate only local, minimal governance counts after explicit confirmation of a separate support agreement. No remote access is opened." permission:"idc:admin:compliance:privacy:configure"`
	SupportAgreementConfirmed bool   `json:"supportAgreementConfirmed" v:"required" dc:"Explicit confirmation that a separate support agreement exists" eg:"true"`
	IdempotencyKey            string `json:"idempotencyKey" v:"required|length:16,128" dc:"Random replay key generated by the administrator application" eg:"privacy-export-0123456789abcdef"`
}

type PrivacySupportExportCreateRes struct {
	ExportNo      string `json:"exportNo" dc:"Opaque local support export number" eg:"PSE_0123456789abcdef0123456789abcdef"`
	FileName      string `json:"fileName" dc:"Safe local download file name" eg:"PSE_0123456789abcdef0123456789abcdef.json"`
	Content       string `json:"content" dc:"Redacted local diagnostic document for explicit local download" eg:"{\"schemaVersion\":\"idc-redacted-support-v1\"}"`
	ContentSHA256 string `json:"contentSha256" dc:"Lowercase SHA-256 digest of the returned document" eg:"0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef"`
	CreatedAt     int64  `json:"createdAt" dc:"Creation time as a Unix timestamp in milliseconds" eg:"1787040000000"`
}
