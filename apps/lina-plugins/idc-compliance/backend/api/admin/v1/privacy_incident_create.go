// Privacy incident creation API immediately starts the local response workflow. Input is limited to fixed codes and a safe summary.

package v1

import "github.com/gogf/gf/v2/frame/g"

type PrivacyIncidentCreateReq struct {
	g.Meta         `path:"/admin/compliance/privacy/incidents" method:"post" tags:"IDC Compliance Privacy" summary:"Create a privacy incident" dc:"Immediately rotate sensitive-access ticket generation, block exports, preserve a safe event record, and start the local response workflow." permission:"idc:admin:compliance:privacy:incident"`
	SeverityCode   string `json:"severityCode" v:"required|in:low,medium,high,critical" dc:"Severity: low, medium, high, or critical" eg:"high"`
	SourceCode     string `json:"sourceCode" v:"required|in:unauthorized_attempt,bulk_download,data_loss,manual_report,system_detection" dc:"Detection source: unauthorized_attempt, bulk_download, data_loss, manual_report, or system_detection" eg:"system_detection"`
	SafeSummary    string `json:"safeSummary" v:"required|max-length:2000" dc:"Bounded summary without raw affected records or credentials" eg:"An unusual sensitive export attempt was detected"`
	IdempotencyKey string `json:"idempotencyKey" v:"required|length:16,128" dc:"Random replay key generated by the administrator application" eg:"privacy-incident-0123456789abcdef"`
}

type PrivacyIncidentCreateRes struct {
	Item PrivacyIncidentItem `json:"item" dc:"Created local incident with exports blocked" eg:"{}"`
}
